import Foundation

/// Quyết định có ghi lại một lần copy hay không (DESIGN §8).
public struct PrivacyFilter: Sendable {
    public enum Decision: Sendable, Equatable {
        case record
        case paused
        /// Pasteboard có type đánh dấu nhạy cảm/tạm thời (giá trị là type đó).
        case sensitive(String)
        /// App nguồn nằm trong danh sách loại trừ (giá trị là bundle ID).
        case excludedApp(String)
        /// Người dùng đã chọn "Bỏ qua lần copy tiếp theo".
        case skippedOnce
    }

    /// Các type theo chuẩn nspasteboard.org mà app quản lý mật khẩu/app tự sinh dùng để đánh dấu.
    public static let sensitiveTypes: [String] = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    /// 1Password (7 và 8), Bitwarden, Keychain Access, Passwords.app.
    public static let defaultExcludedBundleIDs: [String] = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
    ]

    public var ignoreSensitiveTypes: Bool
    public var excludedBundleIDs: Set<String>
    /// `Date.distantFuture` nghĩa là tạm dừng đến khi bật lại.
    public var pausedUntil: Date?
    public var skipNext: Bool

    public init(
        ignoreSensitiveTypes: Bool = true,
        excludedBundleIDs: Set<String> = Set(defaultExcludedBundleIDs),
        pausedUntil: Date? = nil,
        skipNext: Bool = false
    ) {
        self.ignoreSensitiveTypes = ignoreSensitiveTypes
        self.excludedBundleIDs = excludedBundleIDs
        self.pausedUntil = pausedUntil
        self.skipNext = skipNext
    }

    public func isPaused(at now: Date) -> Bool {
        guard let pausedUntil else { return false }
        return now < pausedUntil
    }

    /// Thứ tự: tạm dừng → type nhạy cảm → app loại trừ → bỏ qua một lần.
    /// "Bỏ qua lần tiếp theo" chỉ bị tiêu khi lần copy lẽ ra đã được ghi.
    public func evaluate(types: [String], sourceBundleID: String?, now: Date = Date()) -> Decision {
        if isPaused(at: now) { return .paused }
        if ignoreSensitiveTypes, let type = Self.sensitiveTypes.first(where: types.contains) {
            return .sensitive(type)
        }
        if let sourceBundleID, excludedBundleIDs.contains(sourceBundleID) {
            return .excludedApp(sourceBundleID)
        }
        if skipNext { return .skippedOnce }
        return .record
    }
}
