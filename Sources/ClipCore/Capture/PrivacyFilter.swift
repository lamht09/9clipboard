import Foundation

/// Quyết định xử lý một lần copy.
public struct PrivacyFilter: Sendable {
    public enum Decision: Sendable, Equatable {
        case record
        /// Mật khẩu: vẫn ghi nhưng tự xoá sau một thời gian nếu người dùng không giữ lại.
        /// Giá trị là type đánh dấu hoặc bundle ID của app quản lý mật khẩu.
        case recordSensitive(String)
        case paused
        /// Pasteboard có type đánh dấu nội dung tạm thời/tự sinh, không nên ghi (giá trị là type đó).
        case transient(String)
        /// App nguồn nằm trong danh sách loại trừ (giá trị là bundle ID).
        case excludedApp(String)
        /// Người dùng đã chọn "Bỏ qua lần copy tiếp theo".
        case skippedOnce

        public var shouldRecord: Bool {
            switch self {
            case .record, .recordSensitive: true
            case .paused, .transient, .excludedApp, .skippedOnce: false
            }
        }
    }

    /// Type theo chuẩn nspasteboard.org mà app quản lý mật khẩu dùng để đánh dấu mật khẩu.
    public static let concealedTypes: [String] = [
        "org.nspasteboard.ConcealedType",
        "com.agilebits.onepassword",
    ]

    /// Type đánh dấu nội dung tạm thời hoặc do app tự sinh: không ghi.
    public static let transientTypes: [String] = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    /// 1Password (7 và 8), Bitwarden, Keychain Access, Passwords.app: mọi lần copy từ đây coi là mật khẩu.
    public static let passwordManagerBundleIDs: [String] = [
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
    ]

    /// Tắt thì mật khẩu được ghi như mọi lần copy khác (không tự xoá).
    public var detectPasswords: Bool
    public var excludedBundleIDs: Set<String>
    /// `Date.distantFuture` nghĩa là tạm dừng đến khi bật lại.
    public var pausedUntil: Date?
    public var skipNext: Bool

    public init(
        detectPasswords: Bool = true,
        excludedBundleIDs: Set<String> = [],
        pausedUntil: Date? = nil,
        skipNext: Bool = false
    ) {
        self.detectPasswords = detectPasswords
        self.excludedBundleIDs = excludedBundleIDs
        self.pausedUntil = pausedUntil
        self.skipNext = skipNext
    }

    public func isPaused(at now: Date) -> Bool {
        guard let pausedUntil else { return false }
        return now < pausedUntil
    }

    /// Thứ tự: tạm dừng → type tạm thời → app loại trừ → bỏ qua một lần → mật khẩu.
    /// "Bỏ qua lần tiếp theo" chỉ bị tiêu khi lần copy lẽ ra đã được ghi.
    public func evaluate(types: [String], sourceBundleID: String?, now: Date = Date()) -> Decision {
        if isPaused(at: now) { return .paused }
        if let type = Self.transientTypes.first(where: types.contains) { return .transient(type) }
        if let sourceBundleID, excludedBundleIDs.contains(sourceBundleID) {
            return .excludedApp(sourceBundleID)
        }
        if skipNext { return .skippedOnce }
        if detectPasswords {
            if let type = Self.concealedTypes.first(where: types.contains) { return .recordSensitive(type) }
            if let sourceBundleID, Self.passwordManagerBundleIDs.contains(sourceBundleID) {
                return .recordSensitive(sourceBundleID)
            }
        }
        return .record
    }
}
